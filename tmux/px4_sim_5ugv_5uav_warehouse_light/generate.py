# ------------------------------------------------------------------------------------------- session.yml
def sh_list(lines, indent=8):
    """tmuxinator pane: one shell line, written as a plain yaml scalar continued on further lines
    (yaml folds them with spaces) -- or double-quoted where plain yaml would misread it (': ', ' #')."""
    pad = ' ' * indent
    plain = f'{pad}- ' + f'\n{pad}  '.join(lines)
    joined = ' '.join(lines)
    try:
        if yaml.safe_load(plain.strip()) == [joined]:
            return plain
    except yaml.YAMLError:
        pass
    return f'{pad}- ' + json.dumps(joined)


def make_session(n):
    P = range(1, n + 1)
    S = []
    S.append(f'''# GENERATED by generate.py ({n} pairs) -- edit generate.py, not this file.
#
# {n} UGV + UAV pairs doing warehouse shelf inspection at the same time, each one a copy of
# ../px4_sim_2ugv_2uav_warehouse_stereo_larger's pairs (rbl_controller on both vehicles, UAV carried on
# the UGV deck, PX4 precision landing on its ArUco board), with its own mission node. Lighter for gz:
# headless, no shadows, static visuals merged into a few meshes, gz without PX4's camera streaming,
# {LIGHT['depth_w']}x{LIGHT['depth_h']} depth cameras, down cameras rendered only while their pair lands. README.md has the details.
#
#   ./start.sh      then, once every px4_bridge pane printed 'Arming' / 'px4_bridge started':
#   ./deploy.sh pair <k> row <r> column <c> <left|right>    (all {n} prepared in the `mission` window history)
#   ./deploy.sh abort                                       every pair holds
#   ./kill.sh
root: ./
name: {SESSION}
socket_name: {SOCKET}
attach: false
tmux_options: -f ./tmux.conf
startup_window: mission
pre_window:
  - . ./env.sh
  - if [ "$PIN_CPUS" = 1 ]; then taskset -cp $OTHER_CPUS $$ >/dev/null; fi
  # PX4 spawns only from its own Tools/simulation/gz/{{worlds,models}}: link this folder's in
  - for w in ./worlds/*.sdf; do ln -sfn "$(readlink -f $w)" "$PX4_DIR/Tools/simulation/gz/worlds/$(basename $w)" 2>/dev/null; done
  - for m in ./models/*/; do ln -sfn "$(readlink -f $m)" "$PX4_DIR/Tools/simulation/gz/models/$(basename $m)" 2>/dev/null; done
  - if [ -n "$ZSH_VERSION" ]; then RSH=zsh; else RSH=bash; fi
  - source /opt/ros/jazzy/setup.$RSH
  - source ${{IRBL_INSTALL:-../../../../install}}/setup.$RSH
  - export ATUIN_FILTER_MODE=session
windows:''')

    # --- mission: coordinators + operator pane
    panes = []
    for k in P:
        panes.append(sh_list([
            f'until ros2 service list 2>/dev/null | grep -q "/{ugv(k)}/rbl_controller/goto" &&',
            f'ros2 service list 2>/dev/null | grep -q "/{uav(k)}/warehouse_inspection/inspect"; do sleep 1; done;',
            f'ros2 run rbl_mission ugv_uav_mission_node --ros-args -r __node:=ugv_uav_mission_{k}',
            '--params-file ./config/warehouse_map.yaml -p use_sim_time:=true',
            '-p map.world_sdf:=$(readlink -f ./worlds/$PX4_GZ_WORLD.sdf)',
            f'-p ugv:={ugv(k)} -p uav:={uav(k)} -p detach_topic:=/{ugv(k)}/uav_detach',
            f'-p attach_topic:=/{ugv(k)}/uav_attach -p planner.mode:=$PLANNER']))
    cmds = [f'./deploy.sh pair {k} row {r} column {c} {s}' for k, (r, c, s) in zip(P, DEPLOY)]
    all_cmd = ' ; '.join(cmds)
    hist = ['./deploy.sh abort'] + cmds[::-1] + [all_cmd]   # last = first on arrow-up
    zsh = '; '.join(f"print -s '{h}'" for h in hist)
    bash = '; '.join(f"history -s '{h}'" for h in hist)
    panes.append(sh_list([
        f'echo "Wait for \'Arming\' in the px4_bridge window (all {n} UGVs) and ~30 s more, then arrow-up:',
        f'all {n} pairs at once, or one ./deploy.sh pair <k> ... line each   (./deploy.sh map, ./deploy.sh -h, ./deploy.sh abort)";',
        f'if [ -n "$ZSH_VERSION" ]; then {zsh};',
        f'else {bash}; fi']))
    S.append('  - mission:\n      layout: tiled\n      panes:\n' + '\n'.join(panes))

    # --- states: one pane per pair, mission phase + UAV task
    panes = []
    for k in P:
        panes.append(sh_list([
            f'(ros2 topic echo /ugv_uav_mission_{k}/state std_msgs/msg/String --qos-durability transient_local --field data &',
            f'ros2 topic echo /{uav(k)}/warehouse_inspection/state std_msgs/msg/String --qos-durability transient_local',
            f'--field data | sed -u "s/^/  {uav(k)}: /"; wait)']))
    S.append('  - states:\n      layout: tiled\n      panes:\n' + '\n'.join(panes))

    S.append('''  - micro_xrce_agent:
      layout: tiled
      panes:
        # one agent serves every PX4 instance (each in its own namespace)
        - MicroXRCEAgent udp4 -p 8888''')
    # gz started here, not by PX4 instance 0: own server config (config/gz_server.config, PX4's without the
    # GstCameraSystem that H.264-streams every camera); every PX4 instance attaches to it (PX4_GZ_STANDALONE)
    S.append('''  - gz:
      layout: tiled
      panes:
        - . $PX4_DIR/build/px4_sitl_default/rootfs/gz_env.sh && export GZ_SIM_SERVER_CONFIG_PATH=$(readlink -f ./config/gz_server.config) &&
          W=$PX4_DIR/Tools/simulation/gz/worlds/$PX4_GZ_WORLD.sdf &&
          if [ "$PIN_CPUS" = 1 ]; then taskset -c $GZ_CPUS gz sim --verbose=1 -r -s $W; else gz sim --verbose=1 -r -s $W; fi
        - if [ -z "$HEADLESS" ]; then until gz topic -l 2>/dev/null | grep -q "/world/$PX4_GZ_WORLD/clock"; do sleep 1; done;
          . $PX4_DIR/build/px4_sitl_default/rootfs/gz_env.sh && gz sim -g; else echo "headless (HEADLESS=0 ./start.sh for the gz GUI)"; fi''')

    # --- PX4
