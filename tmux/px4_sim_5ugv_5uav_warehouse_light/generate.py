def make_rviz(n):
    r = yaml.safe_load(open(os.path.join(SRC, 'ugv_uav_2pairs.rviz')))
    disp = r['Visualization Manager']['Displays']
    glob = [d for d in disp if not str(d.get('Name', '')).startswith('[')]
    tmpl = [d for d in disp if str(d.get('Name', '')).startswith('[1]')]
    heavy = ('stereo (raw)', 'sensing cell', 'cell A', 'centroid', 'goal', 'landing', 'debug')

    def retopic(v, k):
        if not isinstance(v, str):
            return v
        v = v.replace('/mission_viz/vehicles', '/mission_viz/vehicles' if k == 1 else f'/mission_viz_{k}/vehicles')
        v = v.replace('ugv_uav_mission_1', f'ugv_uav_mission_{k}')
        v = re.sub(r'/(ugv|uav)1/', rf'/\g<1>{k}/', v)
        return v

    out = list(glob)
    for k in range(1, n + 1):
        for d in tmpl:
            d = copy.deepcopy(d)
            d['Name'] = d['Name'].replace('[1]', f'[{k}]')
            if 'Topic' in d and isinstance(d['Topic'], dict):
                d['Topic']['Value'] = retopic(d['Topic']['Value'], k)
            if d.get('Class', '').endswith('/Path'):
                d['Color'] = COLORS[(k - 1) % len(COLORS)]
            if any(h in d['Name'] for h in heavy):  # off by default with this many vehicles
                d['Enabled'] = False
                d['Value'] = False
            out.append(d)
    r['Visualization Manager']['Displays'] = out
    # image panels of the 2-pair layout (debug images) are dropped with their displays
    win = r.get('Window Geometry', {})
    for key in list(win):
        if key.startswith('[') and 'debug' in key:
            del win[key]
    write('ugv_uav_pairs.rviz', yaml.safe_dump(r, sort_keys=False, width=200))


