def strip_comments(sdf):
    return re.sub(r'<!--.*?-->\s*', '', sdf, flags=re.S)


def make_models(n):
    ugv_src = strip_comments(open(os.path.join(SRC, 'models/ugv1_carrier_stereo/model.sdf')).read())
    uav_src = strip_comments(open(os.path.join(SRC, 'models/uav1_x500_stereo/model.sdf')).read())
    for s in (ugv_src, uav_src):  # what LIGHT changes must be there
        assert '<width>160</width>' in s and '<height>120</height>' in s
    assert '<update_rate>20</update_rate>' in uav_src

    def light_depth(s):
        return (s.replace('<width>160</width>', f"<width>{LIGHT['depth_w']}</width>", 1)
                 .replace('<height>120</height>', f"<height>{LIGHT['depth_h']}</height>", 1))

    import importlib.util
    spec = importlib.util.spec_from_file_location('boards', os.path.join(SRC, 'models/make_deck_boards.py'))
    boards = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(boards)

    for k in range(1, n + 1):
        hdr = (f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by generate.py (pair {k}): '
               f'../px4_sim_2ugv_2uav_warehouse_stereo_larger pair-1 model, renamed, depth camera '
               f"{LIGHT['depth_w']}x{LIGHT['depth_h']}. -->\n")
        s = light_depth(ugv_src.split('?>', 1)[1].lstrip())
        s = (s.replace("name='ugv1_carrier_stereo'", f"name='{m_ugv(k)}'")
              .replace('ugv1/stereo_link', f'{ugv(k)}/stereo_link')
              .replace('model://ugv1_carrier_stereo/deck_board_ugv1.png',
                       f'model://{m_ugv(k)}/deck_board_ugv{k}.png')
              .replace('<child_model>uav1_x500_stereo_1</child_model>', f'<child_model>{gz_uav(k)}</child_model>')
              .replace('/ugv1/uav_detach', f'/{ugv(k)}/uav_detach')
              .replace('/ugv1/uav_attach', f'/{ugv(k)}/uav_attach'))
        assert 'ugv1' not in s.replace(f'ugv{k}', '') or k == 1, s
        write(f'models/{m_ugv(k)}/model.sdf', hdr + s)
        write(f'models/{m_ugv(k)}/model.config', model_config(m_ugv(k), f'UGV {k}: r1_rover + cargo deck + depth camera'))
        boards.make(k, os.path.join(HERE, f'models/{m_ugv(k)}/deck_board_ugv{k}.png'))

        s = light_depth(uav_src.split('?>', 1)[1].lstrip())
        s = (s.replace("name='uav1_x500_stereo'", f"name='{m_uav(k)}'")
              .replace('uav1/stereo_link', f'{uav(k)}/stereo_link')
              .replace('uav1/down_cam_link', f'{uav(k)}/down_cam_link')
              .replace('<update_rate>20</update_rate>', f"<update_rate>{LIGHT['down_rate']}</update_rate>"))
        write(f'models/{m_uav(k)}/model.sdf', hdr + s)
        write(f'models/{m_uav(k)}/model.config', model_config(m_uav(k), f'UAV {k}: x500 + depth camera + down camera'))


def model_config(name, desc):
    return (f'<?xml version="1.0"?>\n<model>\n  <name>{name}</name>\n  <version>1.0</version>\n'
            f'  <sdf version="1.9">model.sdf</sdf>\n  <description>{desc} (generate.py)</description>\n</model>\n')


def _pose(e):
    p = e.find('pose')
    v = [float(x) for x in p.text.split()] if p is not None and p.text and p.text.strip() else [0.0] * 6
    return v + [0.0] * (6 - len(v))


def _T(p):
    import numpy as np
    r, pt, y = p[3:6]
    cr, sr, cp, sp, cy, sy = np.cos(r), np.sin(r), np.cos(pt), np.sin(pt), np.cos(y), np.sin(y)
    T = np.eye(4)
    T[:3, :3] = [[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                 [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                 [-sp, cp * sr, cp * cr]]
    T[:3, 3] = p[:3]
    return T


def make_world():
    """worlds/warehouse.sdf with every static box visual merged into one mesh per material
    (models/warehouse_light_visuals/meshes/m<i>.obj), no shadows. Collisions are unchanged (the
    mission's prior map reads them). Why: gz's SceneBroadcaster sends the pose of every visual on
    /world/<world>/pose/info, which EVERY PX4 instance subscribes to -- 1491 poses per message at
    ~50 Hz in the original world; with 10 PX4s that, not physics or rendering, held gz at RTF ~0.5."""
    import xml.etree.ElementTree as ET
    import numpy as np
    tree = ET.parse(os.path.join(HERE, 'worlds/warehouse.sdf'))
    w = tree.getroot().find('world')
    w.set('name', WORLD)
    for e in w.iter('shadows'):
        e.text = 'false'
    for e in w.iter('cast_shadows'):
        e.text = 'false'

    # unit box: 6 faces (normal, 4 corners counter-clockwise seen from outside)
    faces = []
    for ax in range(3):
        for sgn in (1, -1):
            n = np.zeros(3); n[ax] = sgn
            u = np.zeros(3); u[(ax + 1) % 3] = 1
            v = np.cross(n, u)
            c = n * 0.5
            faces.append((n, [c - u / 2 - v / 2, c + u / 2 - v / 2, c + u / 2 + v / 2, c - u / 2 + v / 2]))

    groups = {}  # material xml -> (material element, obj lines, vertex count)
    merged = 0
    for m in w.findall('model'):
        if m.findtext('static', '').strip() != 'true':
            continue
        Tm = _T(_pose(m))
        for l in m.findall('link'):
            Tl = Tm @ _T(_pose(l))
            for vis in list(l.findall('visual')):
                box = vis.find('geometry/box/size')
                if box is None:
                    continue  # the ground plane stays as it is
                size = np.array([float(x) for x in box.text.split()])
                T = Tl @ _T(_pose(vis))
                mat = vis.find('material')
                key = ET.tostring(mat).decode().strip() if mat is not None else ''
                g = groups.setdefault(key, [mat, [], 0])
                R = T[:3, :3]
                for n, corners in faces:
                    nw = R @ n
                    g[1].append('vn %.5f %.5f %.5f' % tuple(nw))
                    nn = len([x for x in g[1] if x.startswith('vn')])
                    for c in corners:
                        p = R @ (c * size) + T[:3, 3]
                        g[1].append('v %.4f %.4f %.4f' % tuple(p))
                    b = g[2]
                    g[1].append(f'f {b + 1}//{nn} {b + 2}//{nn} {b + 3}//{nn} {b + 4}//{nn}')
                    g[2] += 4
                l.remove(vis)
                merged += 1

    mdir = 'models/warehouse_light_visuals'
    write(f'{mdir}/model.config', model_config('warehouse_light_visuals',
                                               'Meshes only: the merged static visuals of worlds/warehouse_light.sdf'))
    model = ET.SubElement(w, 'model', name='warehouse_light_visuals')
    ET.SubElement(model, 'static').text = 'true'
    link = ET.SubElement(model, 'link', name='link')
    for i, (key, (mat, lines, _)) in enumerate(groups.items()):
        write(f'{mdir}/meshes/m{i}.obj', f'# GENERATED by generate.py\no m{i}\n' + '\n'.join(lines) + '\n')
        vis = ET.SubElement(link, 'visual', name=f'merged{i}')
        geo = ET.SubElement(ET.SubElement(vis, 'geometry'), 'mesh')
        ET.SubElement(geo, 'uri').text = f'model://warehouse_light_visuals/meshes/m{i}.obj'
        if mat is not None:
            vis.append(mat)
    body = ET.tostring(tree.getroot(), encoding='unicode')
    write(f'worlds/{WORLD}.sdf', '<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by generate.py: '
          f'worlds/warehouse.sdf, {merged} static visuals merged into {len(groups)} meshes, no shadows -->\n' + body)
    print(f'world: {merged} visuals -> {len(groups)} meshes')


